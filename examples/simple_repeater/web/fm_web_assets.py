# FieldMesh repeater: turns the files of the WiFi dashboard into a C header (FieldMeshWebAssets.h).
#
# Runs before every build of a FieldMesh repeater env (PlatformIO "pre:" extra script) and writes the
# header into the build folder, so nothing generated is committed. The dashboard page and the SVGs are
# stored gzipped (the box sends them as they are, with Content-Encoding: gzip); the font is already
# compressed. Logo, font and contour lines are only loaded from the box, never from the internet.
#
# The files below "/fm/" get a version in their URL (hash of their content), so phones may cache them
# for a year and still load new ones after a firmware update. The page itself is never cached.
#
# topo-*.svg: the contour lines of docs/FieldMesh/brand/topo-*.svg split into one file per colour; the page
# colours them with CSS masks, so one set works for light and dark.
#
# OFL.txt: licence of the Barlow font (SIL OFL 1.1), shipped with the font as the licence asks; linked from
# Setup -> Box.
#
# Standalone (e.g. to look at the result): python3 fm_web_assets.py <out_dir>

import gzip
import hashlib
import os
import sys

# (URL path, file, content type, gzip, cache)
ASSETS = [
    ("/", "dashboard.html", "text/html", True, False),
    ("/fm/barlow-700.woff2", "barlow-700.woff2", "font/woff2", False, True),
    ("/fm/topo-line.svg", "topo-line.svg", "image/svg+xml", True, True),
    ("/fm/topo-fg.svg", "topo-fg.svg", "image/svg+xml", True, True),
    ("/fm/topo-orange.svg", "topo-orange.svg", "image/svg+xml", True, True),
    ("/fm/OFL.txt", "OFL.txt", "text/plain; charset=utf-8", True, True),
]
PAGE_VERSION_TOKEN = b"__V__"


def _carray(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(str(b) for b in data[i:i + 24]))
    return "static const uint8_t %s[] PROGMEM = {\n%s\n};\n" % (name, ",\n".join(lines))


def generate(src_dir, out_dir):
    raw = {}
    for path, fname, ctype, gz, cache in ASSETS:
        with open(os.path.join(src_dir, fname), "rb") as f:
            raw[path] = f.read()
    h = hashlib.sha1()
    for path, fname, ctype, gz, cache in ASSETS:
        if cache:
            h.update(raw[path])
    version = h.hexdigest()[:8].encode()

    parts = [
        "#pragma once\n",
        "// Generated by examples/simple_repeater/web/fm_web_assets.py before the build - do not edit.\n",
        "#include <stdint.h>\n#include <stddef.h>\n\n",
        "struct FmWebAsset { const char* path; const char* type; const uint8_t* data; size_t len; bool gzip; bool cache; };\n\n",
    ]
    table = []
    total = 0
    for i, (path, fname, ctype, gz, cache) in enumerate(ASSETS):
        data = raw[path]
        if path == "/":
            data = data.replace(PAGE_VERSION_TOKEN, version)   # ?v=__V__ in the URLs of the /fm/ files
        if gz:
            data = gzip.compress(data, compresslevel=9, mtime=0)
        total += len(data)
        name = "fm_web_%d" % i
        parts.append(_carray(name, data))
        table.append('  {"%s", "%s", %s, sizeof(%s), %s, %s},' % (path, ctype, name, name,
                                                                  "true" if gz else "false",
                                                                  "true" if cache else "false"))
    parts.append("\nstatic const FmWebAsset FM_WEB_ASSETS[] = {\n%s\n};\n" % "\n".join(table))
    parts.append("static const size_t FM_WEB_ASSET_COUNT = %d;\n" % len(ASSETS))
    parts.append('#define FM_WEB_ASSET_VERSION "%s"\n' % version.decode())
    content = "".join(parts)

    os.makedirs(out_dir, exist_ok=True)
    out = os.path.join(out_dir, "FieldMeshWebAssets.h")
    old = None
    if os.path.exists(out):
        with open(out) as f:
            old = f.read()
    if old != content:   # unchanged header -> no recompile
        with open(out, "w") as f:
            f.write(content)
    return total, version.decode()


try:
    Import("env")  # noqa: F821  (PlatformIO / SCons)
except NameError:
    env = None

if env is not None:
    src = os.path.join(env.subst("$PROJECT_DIR"), "examples", "simple_repeater", "web")
    out = os.path.join(env.subst("$BUILD_DIR"), "fm_web")
    size, ver = generate(src, out)
    print("FieldMesh web assets: %d bytes in flash, version %s" % (size, ver))
    env.Append(CPPPATH=[out])
elif __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    size, ver = generate(here, sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "out"))
    print("%d bytes, version %s" % (size, ver))
