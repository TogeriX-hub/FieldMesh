TEST(FieldMeshTimeZone, AllReferenceRulesParse) {
  for (const char* z : ZONES) {
    FmTz tz;
    EXPECT_TRUE(fmTzParse(z, tz)) << z;
  }
}

TEST(FieldMeshTimeZone, ChangesHappenAtTheRightSecond) {
  for (const TzRef& r : TRANS) {
    FmTz tz;
    ASSERT_TRUE(fmTzParse(ZONES[r.zone], tz));
    SCOPED_TRACE(testing::Message() << ZONES[r.zone] << " t=" << r.t);
    EXPECT_EQ(fmTzOffset(tz, r.t - 1), r.before);
    EXPECT_EQ(fmTzOffset(tz, r.t), r.after);
  }
}

TEST(FieldMeshTimeZone, BrowserRulesGiveTheSameChanges) {
  ASSERT_EQ(sizeof(BROWSER) / sizeof(BROWSER[0]), sizeof(ZONES) / sizeof(ZONES[0]));
  for (const TzRef& r : TRANS) {
    FmTz tz;
    ASSERT_TRUE(fmTzParse(BROWSER[r.zone], tz)) << BROWSER[r.zone];
    SCOPED_TRACE(testing::Message() << BROWSER[r.zone] << " t=" << r.t);
    EXPECT_EQ(fmTzOffset(tz, r.t - 1), r.before);
    EXPECT_EQ(fmTzOffset(tz, r.t), r.after);
  }
}

TEST(FieldMeshTimeZone, OffsetStaysBetweenChanges) {
  // middle of every period between two changes, and zones without changes all year
  const int n = sizeof(TRANS) / sizeof(TRANS[0]);
  for (int i = 0; i + 1 < n; i++) {
    if (TRANS[i].zone != TRANS[i + 1].zone) continue;
    FmTz tz;
    ASSERT_TRUE(fmTzParse(ZONES[TRANS[i].zone], tz));
    const int64_t mid = (TRANS[i].t + TRANS[i + 1].t) / 2;
    EXPECT_EQ(fmTzOffset(tz, mid), TRANS[i].after) << ZONES[TRANS[i].zone];
  }
  const char* fixed[] = { "MST7", "HST10", "IST-5:30", "UTC0", "<+03>-3", "<-03>3" };
  const int32_t off[] = { -7 * 3600, -10 * 3600, 5 * 3600 + 1800, 0, 3 * 3600, -3 * 3600 };
  for (int i = 0; i < 6; i++) {
    FmTz tz;
    ASSERT_TRUE(fmTzParse(fixed[i], tz));
    for (int64_t t = 1767225600; t < 1767225600 + 366LL * 86400; t += 86400 * 7) {
      EXPECT_EQ(fmTzOffset(tz, t), off[i]) << fixed[i];
    }
  }
}

TEST(FieldMeshTimeZone, LocalTime) {
  FmTz tz;
  ASSERT_TRUE(fmTzParse("CET-1CEST,M3.5.0,M10.5.0/3", tz));
  int32_t off = 0;
  // 2026-11-04 10:22 UTC -> 11:22 CET
  EXPECT_EQ(fmTzLocal(tz, 1793787720LL, &off), 1793787720LL + 3600);
  EXPECT_EQ(off, 3600);
  // 2026-07-01 12:00 UTC -> 14:00 CEST
  EXPECT_EQ(fmTzLocal(tz, 1782907200LL, &off), 1782907200LL + 7200);
  EXPECT_EQ(off, 7200);
}

